    overflow=[]
    def wrap(value,font,size,max_width):
        words=value.split();result=[];line=''
        for word in words:
            new=(line+' '+word).strip()
            if line and pdfmetrics.stringWidth(new,font,size)>max_width:
                result.append(line);line=word
            else:line=new
        return result+[line] if line else result or ['']
    for i,slide in enumerate(prs.slides,1):
        c.setFillColorRGB(*[int(NAVY[j:j+2],16)/255 for j in (0,2,4)])
