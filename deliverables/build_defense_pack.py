                if sh.auto_shape_type==MSO_SHAPE.OVAL:c.ellipse(x,height-y-h,x+w,height-y,fill=1,stroke=0)
                elif sh.auto_shape_type==MSO_SHAPE.ROUNDED_RECTANGLE:c.roundRect(x,height-y-h,w,h,min(w,h)*.1,fill=1,stroke=0)
