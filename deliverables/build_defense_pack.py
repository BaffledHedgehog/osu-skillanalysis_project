def color(v): return RGBColor.from_string(v)


def box(slide, x, y, w, h, fill=PANEL, radius=True, line=None):
    shape = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE if radius else MSO_SHAPE.RECTANGLE,
                                   Inches(x), Inches(y), Inches(w), Inches(h))
    shape.fill.solid(); shape.fill.fore_color.rgb = color(fill)
    if line: shape.line.color.rgb = color(line)
    else: shape.line.fill.background()
    if radius:
        try: shape.adjustments[0] = .12
        except IndexError: pass
    return shape


def text(slide, value, x, y, w, h, size=20, fill=WHITE, bold=False, font='Arial', align=None):
    tb = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame; tf.clear(); tf.word_wrap = True
    tf.margin_left = tf.margin_right = Inches(.015)
    tf.margin_top = tf.margin_bottom = Inches(.01)
    for i, line in enumerate(clean(value).split('\n')):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.text = line; p.font.name = font; p.font.size = Pt(size); p.font.bold = bold
        p.font.color.rgb = color(fill); p.space_after = Pt(7)
        if align is not None: p.alignment = align
    return tb


