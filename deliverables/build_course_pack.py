def raci_for_wbs(wbs):
    milestone_package = {
        "1.4": "1.3", "2.6": "2.5",
        "4.3": "4.2", "5.4": "5.3",
    }
    wbs = milestone_package.get(wbs, wbs)
    group, number = map(int, wbs.split("."))
    for code, _, *cells in RACI_ROWS:
        first, _, last = code.partition("-")
        first_group, first_number = map(int, first.split("."))
        last_number = int(last.split(".")[-1]) if last else first_number
        if group == first_group and first_number <= number <= last_number:
            return {
                letter: ", ".join(role for role, cell in zip(RACI_ROLES, cells) if letter in cell)
                for letter in "RACI"
            }
    raise ValueError(f"No RACI package for WBS {wbs}")


