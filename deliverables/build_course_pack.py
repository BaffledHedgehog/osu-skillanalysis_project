def build_projectlibre_xml(entries, duration):
    ns = "http://schemas.microsoft.com/project"
    ET.register_namespace("", ns)
    q = lambda name: f"{{{ns}}}{name}"
    project = ET.Element(q("Project"))
    def tag(parent, name, value):
        ET.SubElement(parent, q(name)).text = str(value)
    tag(project, "SaveVersion", 14)
    tag(project, "Name", "pulse! - MVP")
    tag(project, "Title", "pulse! - календарный план")
    tag(project, "ScheduleFromStart", 1)
    tag(project, "StartDate", f"{START.isoformat()}T09:00:00")
    tag(project, "FinishDate", f"{workday(duration - 1).isoformat()}T18:00:00")
    tag(project, "MinutesPerDay", 480)
    tag(project, "MinutesPerWeek", 2400)
    tag(project, "DaysPerMonth", 20)
    tag(project, "DefaultStartTime", "09:00:00")
    tag(project, "DefaultFinishTime", "18:00:00")
    tag(project, "CalendarUID", 1)
    calendars = ET.SubElement(project, q("Calendars"))
    calendar = ET.SubElement(calendars, q("Calendar"))
    for key, value in (("UID", 1), ("Name", "Пн-Пт"), ("IsBaseCalendar", 1), ("BaseCalendarUID", -1)):
        tag(calendar, key, value)
    weekdays = ET.SubElement(calendar, q("WeekDays"))
    for day_type in range(1, 8):
        weekday = ET.SubElement(weekdays, q("WeekDay"))
        tag(weekday, "DayType", day_type)
        working = day_type in (2, 3, 4, 5, 6)
        tag(weekday, "DayWorking", int(working))
        if working:
            times = ET.SubElement(weekday, q("WorkingTimes"))
            for start, end in (("09:00:00", "13:00:00"), ("14:00:00", "18:00:00")):
                wt = ET.SubElement(times, q("WorkingTime"))
                tag(wt, "FromTime", start)
                tag(wt, "ToTime", end)
    tasks = ET.SubElement(project, q("Tasks"))
    uid_by_id = {row["id"]: index for index, row in enumerate(entries, 1)}
    for index, row in enumerate(entries, 1):
        task = ET.SubElement(tasks, q("Task"))
        raci = raci_for_wbs(row["wbs"])
        raci_note = "; ".join(f"{letter}: {raci[letter] or '-'}" for letter in "RACI")
        for key, value in (("UID", index), ("ID", index), ("Name", f"{row['wbs']} {row['name']}"),
                           ("Type", 1), ("IsNull", 0), ("WBS", row["wbs"]),
                           ("OutlineNumber", row["wbs"]), ("OutlineLevel", 1),
                           ("Start", f"{row['start'].isoformat()}T09:00:00" if row["duration"] else f"{row['finish'].isoformat()}T18:00:00"),
                           ("Finish", f"{row['finish'].isoformat()}T18:00:00"),
                           ("Duration", f"PT{row['duration'] * 8}H0M0S"),
                           ("DurationFormat", 7), ("Milestone", int(row["duration"] == 0)),
                           ("Summary", 0), ("Critical", int(row["critical"])),
                           ("CalendarUID", 1),
                            ("Notes", f"ID {row['id']}; исполнитель {TEAM[row['owner']]}; выход: {row['output']}. RACI: {raci_note}."),
                            ("Text1", raci["R"]), ("Text2", raci["A"]),
                            ("Text3", raci["C"]), ("Text4", raci["I"])):
            tag(task, key, value)
        for predecessor in row["predecessors"]:
            link = ET.SubElement(task, q("PredecessorLink"))
            tag(link, "PredecessorUID", uid_by_id[predecessor])
            tag(link, "Type", 1)
            tag(link, "CrossProject", 0)
            tag(link, "LinkLag", 0)
            tag(link, "LagFormat", 7)
    tree = ET.ElementTree(project)
    ET.indent(tree, space="  ")
    tree.write(ROOT / "Календарный план - pulse!.xml", encoding="utf-8", xml_declaration=True)


