def workday(index):
    current = START
    count = 0
    while count < index:
        current += timedelta(days=1)
        if current.weekday() < 5:
            count += 1
    return current


def schedule():
    entries = []
    by_id = {}
    for id_, group, wbs, name, duration, predecessors, owner, output in TASKS:
        es = max((by_id[p]["ef"] for p in predecessors), default=0)
        row = dict(id=id_, group=group, wbs=wbs, name=name, duration=duration,
                   predecessors=predecessors, owner=owner, output=output,
                   es=es, ef=es + duration)
        entries.append(row)
        by_id[id_] = row
    successors = defaultdict(list)
    for row in entries:
        for predecessor in row["predecessors"]:
            successors[predecessor].append(row["id"])
    finish = max(row["ef"] for row in entries)
    for row in reversed(entries):
        row["lf"] = min((by_id[s]["ls"] for s in successors[row["id"]]), default=finish)
        row["ls"] = row["lf"] - row["duration"]
        row["float"] = row["ls"] - row["es"]
        row["critical"] = row["float"] == 0
        row["start"] = workday(row["es"] if row["duration"] else max(row["es"] - 1, 0))
        row["finish"] = workday(row["ef"] - 1 if row["duration"] else max(row["ef"] - 1, 0))
    return entries, finish


def set_cell(cell, value):
    cell.text = str(value)
    for paragraph in cell.paragraphs:
        paragraph.paragraph_format.space_after = Pt(2)
        for run in paragraph.runs:
            run.font.name = "Calibri"
            run.font.size = Pt(9)


def add_table(doc, headers, rows, font_size=9):
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, header in enumerate(headers):
        set_cell(table.rows[0].cells[i], header)
        for run in table.rows[0].cells[i].paragraphs[0].runs:
            run.bold = True
            run.font.size = Pt(font_size)
    tr_pr = table.rows[0]._tr.get_or_add_trPr()
    repeat = OxmlElement("w:tblHeader")
    repeat.set(qn("w:val"), "true")
    tr_pr.append(repeat)
    for values in rows:
        cells = table.add_row().cells
        for i, value in enumerate(values):
            set_cell(cells[i], value)
            for run in cells[i].paragraphs[0].runs:
                run.font.size = Pt(font_size)
    doc.add_paragraph()
    return table


def new_doc(title, subtitle, landscape=False):
    doc = Document()
    section = doc.sections[0]
    section.page_width = Cm(29.7 if landscape else 21)
    section.page_height = Cm(21 if landscape else 29.7)
    section.top_margin = Cm(1.7)
    section.bottom_margin = Cm(1.7)
    section.left_margin = Cm(1.8)
    section.right_margin = Cm(1.8)
    normal = doc.styles["Normal"]
    normal.font.name = "Calibri"
    normal.font.size = Pt(10)
    normal.paragraph_format.space_after = Pt(5)
    for heading in ("Title", "Heading 1", "Heading 2"):
        doc.styles[heading].font.name = "Calibri"
    doc.add_heading(title, level=0)
    doc.add_paragraph(subtitle)
    footer = section.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    footer.text = f"pulse! | Версия {VERSION} | {VERSION_DATE}"
    return doc


def numbered(doc, items):
    for index, item in enumerate(items, 1):
        doc.add_paragraph(f"{index}. {item}")


